import { build } from "esbuild";
import { mkdir, writeFile, readFile } from "node:fs/promises";

const result=await build({ entryPoints:["scripts/pdf-entry.ts"],bundle:true,format:"esm",platform:"browser",target:["es2020"],minify:true,write:false,external:["node:*","@napi-rs/canvas"],legalComments:"inline" });
const source=result.outputFiles[0].text;
await mkdir("src/importing/generated",{recursive:true});
await writeFile("src/importing/generated/pdf-runtime.ts",`// Generated by pnpm build:pdf. PDF.js Apache-2.0: third-party/PDFJS-LICENSE.\nexport const PDF_RUNTIME = ${JSON.stringify(source)};\n`);
await mkdir("third-party",{recursive:true});
await writeFile("third-party/PDFJS-LICENSE",await readFile("node_modules/pdfjs-dist/LICENSE"));
process.stdout.write(`Local PDF runtime built (${source.length} characters).\n`);
